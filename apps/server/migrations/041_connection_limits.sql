CREATE TABLE IF NOT EXISTS connection_limits (
  id INTEGER PRIMARY KEY CHECK(id=1),
  per_user INTEGER NOT NULL DEFAULT 4 CHECK(per_user BETWEEN 1 AND 128),
  per_device INTEGER NOT NULL DEFAULT 4 CHECK(per_device BETWEEN 1 AND 128),
  terminal_total INTEGER NOT NULL DEFAULT 32 CHECK(terminal_total BETWEEN 1 AND 1024),
  ssh_total INTEGER NOT NULL DEFAULT 64 CHECK(ssh_total BETWEEN 1 AND 1024),
  ssh_per_ip INTEGER NOT NULL DEFAULT 16 CHECK(ssh_per_ip BETWEEN 1 AND 1024),
  revision INTEGER NOT NULL DEFAULT 0,
  updated_at INTEGER
) STRICT;
INSERT OR IGNORE INTO connection_limits(id) VALUES(1);
